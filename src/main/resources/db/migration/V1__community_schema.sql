CREATE TABLE ums_user (
 id INT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(32) NOT NULL UNIQUE,
 alias VARCHAR(64) NOT NULL, password VARCHAR(100) NOT NULL, avatar VARCHAR(255),
 email VARCHAR(128) NOT NULL UNIQUE, mobile VARCHAR(32), bio VARCHAR(255), score INT NOT NULL DEFAULT 0,
 token VARCHAR(255), active BOOLEAN NOT NULL DEFAULT FALSE, status BOOLEAN NOT NULL DEFAULT TRUE,
 role_id INT, auth_version BIGINT NOT NULL DEFAULT 0,
 create_time TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), modify_time TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
);
CREATE TABLE bms_post (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, title VARCHAR(160) NOT NULL, content TEXT NOT NULL,
 comments INT NOT NULL DEFAULT 0, collects INT NOT NULL DEFAULT 0, view INT NOT NULL DEFAULT 0,
 section_id INT NOT NULL DEFAULT 0, top BOOLEAN NOT NULL DEFAULT FALSE, essence BOOLEAN NOT NULL DEFAULT FALSE,
 version BIGINT NOT NULL DEFAULT 0,
 create_time TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), modify_time TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(user_id) REFERENCES ums_user(id)
);
CREATE INDEX idx_post_created ON bms_post(create_time,id);
CREATE INDEX idx_post_author ON bms_post(user_id,create_time,id);
CREATE TABLE bms_tag (id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(32) NOT NULL UNIQUE, topic_count INT NOT NULL DEFAULT 0);
CREATE TABLE bms_post_tag (
 id INT AUTO_INCREMENT PRIMARY KEY, topic_id INT NOT NULL, tag_id INT NOT NULL,
 CONSTRAINT uq_post_tag UNIQUE(topic_id,tag_id),
 FOREIGN KEY(topic_id) REFERENCES bms_post(id) ON DELETE CASCADE,
 FOREIGN KEY(tag_id) REFERENCES bms_tag(id)
);
CREATE TABLE bms_billboard (id INT AUTO_INCREMENT PRIMARY KEY, content VARCHAR(255), create_time TIMESTAMP(6), is_visible BOOLEAN NOT NULL DEFAULT FALSE);
CREATE TABLE bms_tip (id INT AUTO_INCREMENT PRIMARY KEY, content VARCHAR(255), author VARCHAR(255), type BOOLEAN NOT NULL DEFAULT TRUE);
CREATE TABLE bms_promotion (id INT AUTO_INCREMENT PRIMARY KEY, title VARCHAR(255), link VARCHAR(255), description VARCHAR(255));
